import test from "node:test";
import assert from "node:assert/strict";
import mongoose from "mongoose";
import express from "express";
import request from "supertest";
import { User } from "../src/models/User.js";
import { Hospital } from "../src/models/Hospital.js";
import { ProviderMembership } from "../src/models/ProviderMembership.js";
import { IntegrationCredential } from "../src/models/IntegrationCredential.js";
import { OrganizationUsage } from "../src/models/OrganizationUsage.js";
import { AuditLog } from "../src/models/AuditLog.js";
import { ResourceInventory } from "../src/models/ResourceInventory.js";
import { InventoryObservation } from "../src/models/InventoryObservation.js";
import { createIntegrationCredential, authenticateIntegrationCredential, revokeIntegrationCredential, listIntegrationCredentials } from "../src/services/integrationCredentials.js";
import { consumeOrganizationQuota } from "../src/services/organizationQuota.js";
import { assertProviderPermission } from "../src/services/providerPermissions.js";
import { assignedContext } from "../src/services/providerAccess.js";
import { updateInventory } from "../src/services/inventoryService.js";
import { updateMembershipAccess } from "../src/services/providerAdoption.js";
import { addAssignment } from "../src/services/providerAccounts.js";
import { AuthToken } from "../src/models/AuthToken.js";
import { issueSession } from "../src/services/authTokenService.js";
import integrationsRouter from "../src/routes/integrations.js";
const uri = process.env.MEDREACH_ADOPTION_TEST_MONGO_URI;
const isolated = Boolean(uri && /^mongodb:\/\/(127\.0\.0\.1|localhost):\d+\/medreach_adoption_test$/.test(uri));
test("organisation integrations and shared usage limits", { skip: !isolated, timeout: 60000 }, async t => {
  await mongoose.connect(uri, { serverSelectionTimeoutMS: 4000 }); await mongoose.connection.dropDatabase();
  t.after(async () => { await mongoose.connection.dropDatabase(); await mongoose.disconnect(); });
  await Promise.all([User, Hospital, ProviderMembership, IntegrationCredential, OrganizationUsage, AuditLog, ResourceInventory, InventoryObservation].map(M => M.init()));
  const [owner, reporter, reviewer] = await User.create(["owner", "reporter", "reviewer"].map(name => ({ name, email: `${name}@adoption.example`, role: "provider_admin", accountStatus: "active" })));
  const hospital = await Hospital.create({ name: "Adoption isolated hospital", approvalStatus: "approved" });
  const other = await Hospital.create({ name: "Other adoption hospital", approvalStatus: "approved" });
  for (const [user, accessLevel] of [[owner, "admin"], [reporter, "inventory_reporter"], [reviewer, "reviewer"]]) await ProviderMembership.create({ user: user._id, kind: "hospital", organization: hospital._id, accessLevel, assignedBy: owner._id });
  const target = { kind: "hospital", organizationId: String(hospital._id) }, actor = { id: String(owner._id) };
  const provision = scopes => createIntegrationCredential({ ...target, actor, label: "Isolated integration", scopes });
  await t.test("restricted memberships receive inventory permissions without management IDs", async () => {
    for (const user of [reporter, reviewer]) assert.deepEqual((await assignedContext({ id: user._id, role: "provider_admin" })).hospitalIds, []);
    assert.deepEqual((await assignedContext({ id: owner._id, role: "provider_admin" })).hospitalIds, [String(hospital._id)]);
    await assertProviderPermission({ ...target, actor: { id: reporter._id }, permission: "inventory:write" });
    await assertProviderPermission({ ...target, actor: { id: reviewer._id }, permission: "inventory:read" });
    await assert.rejects(assertProviderPermission({ ...target, actor: { id: reviewer._id }, permission: "inventory:write" }), e => e.status === 403);
    await assert.rejects(createIntegrationCredential({ ...target, actor: { id: reporter._id }, label: "Forged", scopes: ["inventory:read"] }), e => e.status === 403);
  });
  await t.test("credentials return one random secret, store only hash, and enforce scopes", async () => {
    const first = await provision(["inventory:read"]), second = await provision(["inventory:read"]);
    assert.notEqual(first.token, second.token);
    const page = await listIntegrationCredentials({ ...target, actor, limit: 1 });
    assert.equal(page.data.length, 1); assert.ok(page.nextCursor);
    const next = await listIntegrationCredentials({ ...target, actor, limit: 1, before: page.nextCursor });
    assert.equal(next.data.length, 1); assert.notEqual(String(next.data[0]._id), String(page.data[0]._id));
    assert.equal(JSON.stringify(page).includes("secretHash"), false);
    await assert.rejects(listIntegrationCredentials({ ...target, actor, before: "forged" }), e => e.status === 400);
    const stored = await IntegrationCredential.findById(first.id).select("+secretHash").lean();
    assert.equal(stored.secretHash.length, 64); assert.equal(JSON.stringify(stored).includes(first.token.split(".")[1]), false);
    assert.equal(JSON.stringify(await AuditLog.find().lean()).includes(first.token), false);
    assert.equal((await authenticateIntegrationCredential(first.token, "inventory:read")).organizationId, target.organizationId);
    await assert.rejects(authenticateIntegrationCredential(first.token, "inventory:write"), e => e.status === 403);
    await assert.rejects(authenticateIntegrationCredential(`${first.token.slice(0, -1)}!`, "inventory:read"), e => e.status === 401);
    await revokeIntegrationCredential({ ...target, actor, id: first.id });
    await assert.rejects(authenticateIntegrationCredential(first.token, "inventory:read"), e => e.status === 401);
  });
  await t.test("machine endpoint derives organisation, rejects cookie fallback and forged body IDs", async () => {
    const key = await provision(["inventory:read", "inventory:write"]);
    const app = express(); app.use(express.json()); app.use("/api/integrations", integrationsRouter);
    assert.equal((await request(app).get("/api/integrations/inventory").set("Cookie", "token=fake")).status, 401);
    const input = { capacity: 50, occupied: 10, blocked: 0, held: 0, expectedVersion: 0, observedAt: new Date().toISOString(), reportingMethod: "provider_report" };
    assert.equal((await request(app).put("/api/integrations/inventory/general_beds").set("Authorization", `Bearer ${key.token}`).send({ ...input, organizationId: String(other._id) })).status, 400);
    assert.equal((await request(app).put("/api/integrations/inventory/general_beds").set("Authorization", `Bearer ${key.token}`).send(input)).status, 200);
    assert.equal(await ResourceInventory.countDocuments({ organization: other._id }), 0);
    assert.equal((await request(app).put("/api/integrations/inventory/general_beds").set("Authorization", `Bearer ${key.token}`).send(input)).status, 409);
    await assert.rejects(updateInventory({ ...target, actor: { id: reviewer._id }, resourceKey: "icu_beds", input }), e => e.status === 403);
  });
  await t.test("membership, account, expiry, archival and password-version changes invalidate keys", async () => {
    const key = await provision(["inventory:read"]);
    await ProviderMembership.updateOne({ user: owner._id }, { $set: { active: false } });
    await assert.rejects(authenticateIntegrationCredential(key.token, "inventory:read"), e => e.status === 403);
    await ProviderMembership.updateOne({ user: owner._id }, { $set: { active: true } });
    await User.updateOne({ _id: owner._id }, { $set: { accountStatus: "disabled" } });
    await assert.rejects(authenticateIntegrationCredential(key.token, "inventory:read"), e => e.status === 403);
    await User.updateOne({ _id: owner._id }, { $set: { accountStatus: "active" }, $inc: { authVersion: 1 } });
    await assert.rejects(authenticateIntegrationCredential(key.token, "inventory:read"), e => e.status === 401);
    const fresh = await provision(["inventory:read"]);
    await Hospital.updateOne({ _id: hospital._id }, { $set: { archivedAt: new Date() } });
    await assert.rejects(authenticateIntegrationCredential(fresh.token, "inventory:read"), e => e.status === 403);
    await Hospital.updateOne({ _id: hospital._id }, { $unset: { archivedAt: 1 } });
    await IntegrationCredential.updateOne({ _id: fresh.id }, { $set: { expiresAt: new Date(0) } });
    await assert.rejects(authenticateIntegrationCredential(fresh.token, "inventory:read"), e => e.status === 401);
  });
  await t.test("machine keys cannot bypass live demo or manual-credential environment restrictions", async () => {
    const key = await provision(["inventory:read"]);
    try {
      await User.updateOne({ _id: owner._id }, { $set: { demoAccount: true } });
      await assert.rejects(authenticateIntegrationCredential(key.token, "inventory:read"), e => e.status === 403);
      await assert.rejects(provision(["inventory:read"]), e => e.status === 403);
      await User.updateOne({ _id: owner._id }, { $set: { demoAccount: false, credentialDelivery: "manual" } });
      await assert.rejects(authenticateIntegrationCredential(key.token, "inventory:read"), e => e.status === 403);
      await assert.rejects(provision(["inventory:read"]), e => e.status === 403);
    } finally { await User.updateOne({ _id: owner._id }, { $set: { demoAccount: false, credentialDelivery: "invitation" } }); }
    assert.equal((await authenticateIntegrationCredential(key.token, "inventory:read")).organizationId, target.organizationId);
  });
  await t.test("staff assignment starts restricted and access edits use scoped version checks and session revocation", async () => {
    await Hospital.updateOne({ _id: other._id }, { $set: { verificationStatus: "verified" } });
    const initial = await addAssignment(reporter, { kind: "hospital", organizationId: other._id, accessLevel: "inventory_reporter" }, owner._id);
    assert.equal(initial.accessLevel, "inventory_reporter");
    await assert.rejects(addAssignment(reporter, { kind: "hospital", organizationId: other._id, accessLevel: "admin" }, owner._id), e => e.status === 409);
    assert.equal((await ProviderMembership.findById(initial._id)).accessLevel, "inventory_reporter");
    const member = await ProviderMembership.findOne({ user: reviewer._id, organization: hospital._id }).lean();
    const legacy = await issueSession(reviewer);
    const input = { accessLevel: "inventory_reporter", expectedUpdatedAt: member.updatedAt.toISOString(), reason: "Reviewed inventory reporting responsibility" };
    await assert.rejects(updateMembershipAccess({ actor: { id: reporter._id }, membershipId: member._id, input }), e => e.status === 403);
    const outcome = await updateMembershipAccess({ actor, membershipId: member._id, input });
    assert.equal(outcome.changed, true); assert.equal(outcome.accessLevel, "inventory_reporter");
    assert.ok((await AuthToken.findById(legacy.entry._id)).revokedAt);
    const committed = await ProviderMembership.findById(member._id).select("+accessAudit").lean();
    assert.equal(committed.accessAudit.length, 1); assert.equal(committed.accessAudit[0].after, "inventory_reporter");
    await assert.rejects(updateMembershipAccess({ actor, membershipId: member._id, input: { ...input, accessLevel: "reviewer" } }), e => e.status === 409);
    const ownerMember = await ProviderMembership.findOne({ user: owner._id, organization: hospital._id }).lean();
    await assert.rejects(updateMembershipAccess({ actor, membershipId: ownerMember._id, input: { ...input, accessLevel: "reviewer", expectedUpdatedAt: ownerMember.updatedAt.toISOString() } }), e => e.code === "LAST_PROVIDER_ADMIN");
    assert.equal((await User.findById(reviewer._id).select("+authVersion")).authVersion, 1);
  });
  await t.test("parallel replicas consume a bounded shared quota and reset by time window", async () => {
    const now = new Date("2026-01-01T00:00:00Z");
    const outcomes = await Promise.allSettled(Array.from({ length: 25 }, () => consumeOrganizationQuota({ kind: "hospital", organizationId: other._id, operation: "import", now })));
    assert.equal(outcomes.filter(r => r.status === "fulfilled").length, 10);
    assert.equal(outcomes.filter(r => r.status === "rejected" && r.reason.status === 429).length, 15);
    assert.equal((await OrganizationUsage.findOne({ organization: other._id, operation: "import" })).used, 10);
    assert.equal((await consumeOrganizationQuota({ kind: "hospital", organizationId: other._id, operation: "import", now: new Date(now.getTime() + 3600000) })).remaining, 9);
  });
});
